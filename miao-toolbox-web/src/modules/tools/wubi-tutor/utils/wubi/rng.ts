/**
 * 可复现随机数。
 *
 * 为什么需要它：练习会话刷新后要能**接着刚才那一轮继续**，就必须让题序可复现。
 * 题源是「闭包 + 内部可变状态」（`internal: { pool, used: new Set() }`），
 * `Set` 没法 JSON 序列化，所以「把题源状态存下来」这条路走不通。
 * 但只要随机来源可控，就可以用**同一个种子重建题源、再空转到第 N 题**，
 * 精确复原题序与内部状态 —— 不必序列化任何内部结构。
 *
 * 用的是 mulberry32：状态只有 32 位，实现几行，抽题这种用途绰绰有余。
 * !! 不是加密安全随机，不要用于任何安全用途 !!
 */

export type Rng = () => number;

/** 由种子创建随机数发生器。同一 seed 必然产生同一序列。 */
export function createRng(seed: number): Rng {
  // 归一到 32 位无符号：负数或超大种子会让下面的位运算产生意外行为
  let state = seed >>> 0;

  return function next(): number {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * 生成一个新种子。
 * 只在「开始新一轮练习」时调用一次，随后整轮都用它 —— 调用多次等于没有种子。
 */
export function randomSeed(): number {
  return Math.floor(Math.random() * 0x100000000) >>> 0;
}

/*
 * ── 使用约定：发生器必须随 `init()` 重置 ──
 *
 * 题源把发生器建在**构造处**、由 `init()` 重置回种子起点（见
 * questionSource.ts 各工厂的 `let rng = rngFor(config)` + `init` 内重置）。
 *
 * 为什么不能只在构造时建一次：`init()` 只重建 `used` 集合，随机序号却是
 * 跨 `init()` 累积的。于是只要**同一个题源对象被 start() 两次**（React 严格
 * 模式下的重复调用、重试路径等），第二次就从第 2 个随机数开始 ——
 * 整个题序**整体位移一格**。
 *
 * 线上症状极具迷惑性：刷新后「继续」，恢复出来的是**相邻的那一道题**
 * （刷新前是「主」，继续后是「晝」），而界面、指标、进度全都正常，
 * 唯一的线索就是题目变了。实测同一轮里还会时对时错。
 *
 * 重置之后两条路径严格等价：
 *   实时 = init() + 逐题 next()      （可能被 start 多次，但每次 init 都归零）
 *   恢复 = init() + 空转 N 次 next()
 * 这正是中断恢复成立的前提，也是它唯一能站住脚的地方。
 */
